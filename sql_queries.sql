-- Новая таблица сотрудников
SELECT * FROM Сотрудник;

-- Объединенный результат
SELECT 
    s.КодСотрудника,
    s.ФиоСотрудника,
    s.КодДолжности,
    d.НазвДолжности
FROM Сотрудник s
JOIN Должность d ON s.КодДолжности = d.КодДолжности;