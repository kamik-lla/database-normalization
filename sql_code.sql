-- Создание таблицы должностей
CREATE TABLE Должность (
    КодДолжности INT PRIMARY KEY,
    НазвДолжности VARCHAR(100) NOT NULL UNIQUE
);

-- Перенос уникальных должностей
INSERT INTO Должность (КодДолжности, НазвДолжности)
SELECT DISTINCT КодДолжности, НазвДолжности
FROM Сотрудник_Исходная;

-- Создание нормализованной таблицы сотрудников
CREATE TABLE Сотрудник (
    КодСотрудника INT PRIMARY KEY,
    ФиоСотрудника VARCHAR(100) NOT NULL,
    КодДолжности INT NOT NULL,
    FOREIGN KEY (КодДолжности) REFERENCES Должность(КодДолжности)
);

